import { strFromU8, strToU8, zipSync } from 'fflate';
import { config } from '../config.js';
import { AppError } from '../lib/errors.js';
import { checkExportable, exportWarnings, mapTestCaseToRow } from './edge-case-mapping.js';
import { buildSheetParts, buildTableXml, COLUMN_LETTERS, FIRST_DATA_ROW } from './sheet-builder.js';
import { inspectWorkbook } from './inspect.js';
import { loadTemplate, SHARED_STRINGS_PART, SHEET_PART, TABLE_PART } from './template.js';
import { recordFacts, recordTiming, setStage, trace } from '../lib/trace.js';

/**
 * Fixed so the same input always produces the same bytes. Zip entry timestamps
 * would otherwise make every export differ, which makes the output impossible
 * to diff and the tests impossible to pin. Excel ignores them.
 */
const FIXED_MTIME = new Date('2020-01-01T00:00:00Z');

/**
 * Canonical test cases -> a SIT Script workbook.
 *
 * Deterministic and self-contained: no LLM, no network, no configuration beyond
 * the template path. The office template is read, never written.
 *
 * @param {object[]} testCases   canonical test cases
 * @param {{ templatePath?: string }} [options]
 * @returns {{ buffer: Buffer, rowCount: number, lastRow: number, tableRef: string|null, warnings: object[] }}
 */
export function exportSitScript(testCases, options = {}) {
  const templatePath = options.templatePath ?? config.templatePath;
  const startedAt = Date.now();

  setStage('EXPORT');
  trace('export_started', {
    testcase_count: Array.isArray(testCases) ? testCases.length : 0,
  });

  if (!Array.isArray(testCases)) {
    trace('export_failed', { error_code: 'EXPORT_INVALID_INPUT', fail_soft: false });
    throw new AppError('EXPORT_INVALID_INPUT', 'Test cases must be provided as an array.', 400);
  }

  // Every problem at once. Fixing one blocker only to be shown the next is a
  // bad way to review forty test cases.
  const issues = testCases.flatMap((testCase) => checkExportable(testCase));
  if (issues.length > 0) {
    trace('export_failed', {
      error_code: 'EXPORT_BLOCKED',
      blocked_count: issues.length,
      duration_ms: Date.now() - startedAt,
      fail_soft: false,
    });
    throw new AppError(
      'EXPORT_BLOCKED',
      `${issues.length} test case(s) cannot be exported. Resolve them in review first.`,
      422,
      issues
    );
  }

  // Collected, never acted on. These rows are written exactly as drafted and
  // the notices travel alongside the file so QA knows which cells to look at.
  const warnings = testCases.flatMap((testCase) => exportWarnings(testCase));

  // order_index drives the sheet order and therefore Case ID sequence; case_id
  // breaks ties so the output never depends on row insertion order.
  const ordered = [...testCases].sort(
    (a, b) => (a.order_index ?? 0) - (b.order_index ?? 0) || a.case_id.localeCompare(b.case_id)
  );

  let template;
  let rows;
  let built;

  try {
    template = loadTemplate(templatePath);
    rows = ordered.map((testCase) => mapTestCaseToRow(testCase));
    built = buildSheetParts(template, rows);
  } catch (cause) {
    throw new AppError(
      'EXPORT_GENERATION_FAILED',
      `Could not build the SIT Script workbook: ${cause.message}`,
      500
    );
  }

  // Copy every part through untouched, then swap the three that change. Styles,
  // theme, drawing, persons, workbook and relationships are never regenerated.
  const output = {};
  for (const [name, bytes] of Object.entries(template.parts)) {
    output[name] = bytes;
  }

  output[SHEET_PART] = strToU8(built.sheetXml);
  output[SHARED_STRINGS_PART] = strToU8(built.sharedStringsXml);

  if (template.parts[TABLE_PART] && built.tableRef) {
    output[TABLE_PART] = strToU8(
      buildTableXml(strFromU8(template.parts[TABLE_PART]), built.tableRef)
    );
  }

  const zipOptions = Object.fromEntries(
    Object.keys(output).map((name) => [name, { mtime: FIXED_MTIME }])
  );

  let buffer;
  try {
    buffer = Buffer.from(zipSync(output, zipOptions));
  } catch (cause) {
    throw new AppError(
      'EXPORT_GENERATION_FAILED',
      `Could not package the SIT Script workbook: ${cause.message}`,
      500
    );
  }

  verify(buffer, rows, built);

  recordTiming('export', Date.now() - startedAt);
  recordFacts({ exported_rows: rows.length });
  trace('export_completed', {
    testcase_count: testCases.length,
    row_count: rows.length,
    last_row: built.lastRow,
    warning_count: warnings.length,
    output_bytes: buffer.length,
    duration_ms: Date.now() - startedAt,
  });

  return {
    buffer,
    rowCount: rows.length,
    lastRow: built.lastRow,
    tableRef: built.tableRef,
    warnings,
  };
}

/**
 * Reads the generated bytes back and checks them against what was asked for.
 *
 * PRD 22: never hand over a partially corrupted workbook. A failure here means
 * the caller gets a controlled error and no file, rather than a download that
 * fails to open on someone else's machine.
 */
function verify(buffer, rows, built) {
  let workbook;
  try {
    workbook = inspectWorkbook(buffer);
  } catch (cause) {
    throw new AppError(
      'EXPORT_VERIFICATION_FAILED',
      `The generated workbook could not be read back: ${cause.message}`,
      500
    );
  }

  const problems = [];

  if (workbook.dataRows.length !== rows.length) {
    problems.push(`expected ${rows.length} data row(s), found ${workbook.dataRows.length}`);
  }

  if (Object.keys(workbook.headerRow).length !== COLUMN_LETTERS.length) {
    problems.push(`header row has ${Object.keys(workbook.headerRow).length} columns`);
  }

  rows.forEach((row, index) => {
    const actual = workbook.dataRows[index];
    if (!actual) return;

    if (actual.row !== FIRST_DATA_ROW + index) {
      problems.push(`row ${index + 1} landed at sheet row ${actual.row}`);
    }
    if (actual.cells.A !== row.case_id) {
      problems.push(`row ${actual.row} Case ID is '${actual.cells.A}', expected '${row.case_id}'`);
    }
    if (actual.cells.D !== row.case_type) {
      problems.push(
        `row ${actual.row} Case Type is '${actual.cells.D}', expected '${row.case_type}'`
      );
    }
    if (actual.cells.G !== row.expected_result) {
      problems.push(`row ${actual.row} Expected Result did not survive the round trip`);
    }
    if (actual.cells.H !== '' || actual.cells.I !== '') {
      problems.push(`row ${actual.row} has execution fields filled in`);
    }
  });

  for (const validation of workbook.validations) {
    // Compare the parsed end row, not a string suffix: 'D2:D12' ends with '2'.
    const endRow = /:[A-Z]+(\d+)$/.exec(validation.sqref ?? '');
    if (!endRow || Number.parseInt(endRow[1], 10) !== built.lastRow) {
      problems.push(
        `validation '${validation.sqref}' does not end at row ${built.lastRow}, so some rows would lose their dropdown`
      );
    }
  }

  if (problems.length > 0) {
    throw new AppError(
      'EXPORT_VERIFICATION_FAILED',
      'The generated workbook failed its own integrity check and was discarded.',
      500,
      problems
    );
  }
}

/** `SIT Script - Project Name.xlsx`, with characters Windows rejects removed. */
export function exportFilename(projectName) {
  const safe = String(projectName ?? 'Project')
    .replace(/[<>:"/\\|?*\u0000-\u001F]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120);
  return `SIT Script - ${safe || 'Project'}.xlsx`;
}
