import { LLMProvider, LlmError, LLM_ERRORS } from './provider.js';

/**
 * A provider that answers from a script instead of a network.
 *
 * Two jobs. In tests it makes generation deterministic: every case - good
 * output, malformed output, a rate limit, a truncated reply - is an input to a
 * pure function rather than a condition to wait for, and no test ever spends
 * money or needs a key. In development it lets the whole pipeline and UI be
 * exercised offline with `LLM_PROVIDER=mock`.
 *
 * It is a real implementation of the interface, not a stub with the same shape,
 * so it also serves as the check that the abstraction is honest: anything
 * GeminiProvider needs that this cannot express has leaked vendor detail into
 * the contract.
 */
export class MockProvider extends LLMProvider {
  /**
   * @param {object} settings
   * @param {unknown|unknown[]} [settings.responses]  returned in order, last one repeats
   * @param {Error} [settings.failWith]               thrown instead of answering
   */
  constructor(settings = {}) {
    super({ name: 'Mock', model: settings.model ?? 'mock-1' });

    this.settings = settings;
    this.responses = [settings.responses ?? DEFAULT_RESPONSE].flat();
    this.failWith = settings.failWith ?? null;

    /** Every request received, so tests can assert what was and was not sent. */
    this.calls = [];
  }

  async generateJson(request) {
    this.calls.push(request);

    if (this.failWith) throw this.failWith;

    const index = Math.min(this.calls.length - 1, this.responses.length - 1);
    const response = this.responses[index];

    if (response instanceof Error) throw response;

    return {
      data: typeof response === 'function' ? response(request) : response,
      usage: { input_tokens: 0, output_tokens: 0, total_tokens: 0 },
    };
  }
}

/**
 * The default reply, derived from whatever it was asked about.
 *
 * It reads the requirement ids back out of the prompt and answers for those, so
 * `LLM_PROVIDER=mock` drives the whole pipeline - generate, validate, export -
 * with no key and no network. The content is obviously placeholder text; the
 * structure is exactly what a real provider must return.
 */
function DEFAULT_RESPONSE({ prompt, schema }) {
  // A semantic review asks for { issues }. The mock finds nothing wrong, which
  // leaves the deterministic checks as the only findings in offline mode.
  if (schema?.properties?.issues) return { issues: [] };

  const requirementIds = [...new Set(String(prompt ?? '').match(/REQ-\d{3,}/g) ?? [])];

  const testCases = requirementIds.flatMap((requirementId) => [
    {
      requirement_ids: [requirementId],
      section: `Mock section for ${requirementId}`,
      test_case: `Verify the behaviour described by ${requirementId}.`,
      case_type: 'Positive',
      edge_polarity: null,
      priority: 'Medium',
      type: 'Functional',
      expected_result: `Mock expected result for ${requirementId}. Replace by configuring a real provider.`,
      confidence: 'Low',
      warnings: [],
    },
    {
      requirement_ids: [requirementId],
      section: `Mock section for ${requirementId}`,
      test_case: `Verify rejection of the invalid case described by ${requirementId}.`,
      case_type: 'Negative',
      edge_polarity: null,
      priority: 'Medium',
      type: 'Functional',
      expected_result: `Mock rejection result for ${requirementId}. Replace by configuring a real provider.`,
      confidence: 'Low',
      warnings: [],
    },
  ]);

  return {
    project: {
      project_description: 'This is mock output produced without calling a language model.',
      project_summary:
        'LLM_PROVIDER is set to mock, so this content is placeholder text rather than a reading of the requirements.',
      qa_guidance:
        'Nothing here reflects the uploaded documents. Configure a real provider before using any of it.',
      sit_scope: [
        'Mock Scope: Exercising the generation pipeline without a provider.',
        'Mock Scope: Confirming test cases reach validation and export.',
        'Mock Scope: Confirming traceability is derived from the requirements.',
      ],
      project_background:
        'Generated by the mock provider so the pipeline can be run offline. It is not a description of any real project.',
    },
    test_cases: testCases,
    warnings: [
      {
        code: 'MOCK_PROVIDER',
        message:
          'LLM_PROVIDER=mock produced this content without calling a language model. It is placeholder text and must not be used as a SIT script.',
        requirement_id: null,
      },
    ],
  };
}

/** Convenience for the failure-path tests. */
export function llmFailure(code, message = 'Mock provider failure.', status = 502) {
  return new LlmError(LLM_ERRORS[code] ?? code, message, status);
}
